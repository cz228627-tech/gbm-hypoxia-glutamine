###############################################################################
##  01_gateA_lin.R
##  Gate A: Lin et al. scRNA-seq — hypoxia-glutamine association in malignant GBM
##
##  Dataset: Lin et al. 2026, Nat Neurosci
##  File:    gbm_integrated.h5ad (85,597 cells x 30,356 genes, 41 patients)
##  Data already log-normalized (float64, max ~3.6)
##
##  Analysis:
##    1. Load, filter to malignant cells, filter eligible patients (>= 50 cells)
##    2. Score hypoxia, glutamine (11-gene), 5 fate components, 12 programs
##    3. Per-patient Spearman correlation (hypoxia vs glutamine)
##    4. Wilcoxon signed-rank test on 28 patient-level rho values
##    5. Component-level analysis with BH correction
##    6. Synthesis vs catabolism contrast
##    7. Within-state analysis (AC, MES, OPC, NPC)
##    8. 12-program landscape
##
##  *** BUG-AUDIT WARNING (do not skip) ***
##  The archived Python outputs `gateA_component_summary.csv`,
##  `gateA_per_gene_rho.csv`, and the ORIGINAL `gateA_per_patient_rho.csv`
##  (component-level, 140 rows) were confirmed to be STALE / pre-fix files:
##  they were generated by a first analysis round before an artifact caused
##  by `sc.tl.score_genes()`'s control-gene subtraction was discovered and
##  corrected to plain arithmetic-mean scoring (the frozen primary method).
##  For Catabolism and CN_redistribution specifically, the stale files'
##  numbers do NOT match the arithmetic-mean method used throughout this R
##  port (CN_redistribution flips from a null result, 13/28 p=0.60, to a
##  significant negative result, 10/28 p=0.048 -- a QUALITATIVE difference).
##  DO NOT use those two CSVs (or `qa_spatial_null.csv` for the spatial gate)
##  to validate this script's output. Use instead:
##    - `qa_sensitivity_scoring.csv`, rows with "__mean__" in `name`
##      (per-component ground truth)
##    - `qa_endpoint_consistency.csv`, `Lin_11gene`/`Lin_13gene` rows
##      (primary endpoint ground truth)
##  Even among "arithmetic mean" files, `gateA_component_summary.csv`'s
##  Synthesis row (median rho=0.1543) does not exactly match
##  `qa_sensitivity_scoring.csv`'s Fate_Synthesis__mean__hyp_mean row
##  (median rho=0.1627) despite both being mean-based and giving identical
##  Wilcoxon statistics (same rank order, different magnitude) -- this
##  residual discrepancy was not resolved and likely reflects a difference
##  in the upstream hypoxia-score vector between pipeline rounds. It does
##  not change direction/significance for any of the 5 components.
##
##  A THIRD instance of the same score_genes-vs-mean split was found and
##  RESOLVED this revision for the Section 8 contrast: the frozen
##  `gateA_contrast.csv` (16/28 synthesis-favored, p=0.095) is ALSO stale --
##  the authoritative frozen counterpart is `qa_lin_contrast_mean.csv`
##  (24/28, median D=0.1166, p=1.10e-05), which matches the manuscript text
##  exactly ("24/28 tumors, median D=0.117, P<0.0001"). Section 8's output
##  is now written to `qa_lin_contrast_mean.csv` accordingly -- see the
##  in-line comment there for the numeric confirmation.
###############################################################################

source("00_setup.R")
suppressPackageStartupMessages({
  library(zellkonverter)  # read h5ad -> SingleCellExperiment
  library(SingleCellExperiment)
})

# ---- 1. Load Data -----------------------------------------------------------
## Adjust path to your local copy of the h5ad file
h5ad_path <- "data/gbm_integrated.h5ad"

cat("Loading Lin h5ad (may take 1-2 min)...\n")
sce <- readH5AD(h5ad_path)

## Extract expression matrix (cells x genes, already log-normalized)
expr <- t(assay(sce, "X"))  # now cells x genes

## Gene symbols are in rowData column "features"
gene_symbols <- as.character(rowData(sce)$features)
colnames(expr) <- gene_symbols

## Metadata
meta <- as.data.frame(colData(sce))
cat(sprintf("Loaded: %d cells x %d genes, %d patients\n",
            nrow(expr), ncol(expr), length(unique(meta$Patient))))

# ---- 2. Filter to Malignant Cells -------------------------------------------
mal_mask <- meta$annotation %in% malignant_states
expr_mal <- expr[mal_mask, ]
meta_mal <- meta[mal_mask, ]
cat(sprintf("Malignant cells: %d\n", nrow(expr_mal)))

# ---- 3. Filter Eligible Patients (>= 50 malignant cells, exclude 'unknown') -
patient_counts <- table(meta_mal$Patient)
eligible_patients <- names(patient_counts)[patient_counts >= 50 &
                                           names(patient_counts) != "unknown"]
keep <- meta_mal$Patient %in% eligible_patients
expr_mal <- expr_mal[keep, ]
meta_mal <- meta_mal[keep, ]
cat(sprintf("Eligible patients: %d (cells: %d)\n",
            length(eligible_patients), nrow(expr_mal)))

# ---- 4. Score All Modules ---------------------------------------------------
cat("Scoring modules...\n")

## Primary scores
hypoxia_score    <- score_module(expr_mal, hypoxia_genes, colnames(expr_mal))
glutamine_11_score <- score_module(expr_mal, glutamine_11, colnames(expr_mal))

## 5 fate components
component_scores <- sapply(names(fate_components), function(comp) {
  score_module(expr_mal, fate_components[[comp]], colnames(expr_mal))
})
colnames(component_scores) <- names(fate_components)

## 12 metabolic programs (for landscape)
program_scores <- sapply(names(metabolic_programs), function(prog) {
  score_module(expr_mal, metabolic_programs[[prog]], colnames(expr_mal))
})
colnames(program_scores) <- names(metabolic_programs)

cat("Scoring complete.\n")

# ---- 5. Per-Patient Spearman: Hypoxia vs Glutamine (11-gene, primary) -------
cat("\n=== Gate A: Primary Endpoint (11-gene glutamine) ===\n")

patient_rho <- per_patient_spearman(
  hypoxia_score, glutamine_11_score, meta_mal$Patient
)

## Wilcoxon signed-rank test on rho values
primary_test <- signed_rank_test(patient_rho$rho)
cat(sprintf("  Patients positive: %d/%d\n",
            primary_test$n_positive, primary_test$n_total))
cat(sprintf("  Median rho: %.4f\n", primary_test$median))
cat(sprintf("  Wilcoxon p (two-sided): %.2e\n", primary_test$p_value))

## NOTE: renamed from the original `gateA_per_patient_rho.csv`. That filename
## collides with a DIFFERENT real file in the archived Python outputs: a
## 140-row PER-PATIENT-PER-COMPONENT breakdown (columns
## Patient,Component,rho,p,direction,n_cells; 28 patients x 5 components).
## This file is the 28-row PRIMARY endpoint (11-gene) per-patient rho only --
## saved under a distinct name to avoid confusing the two.
fwrite(patient_rho, file.path(results_dir, "gateA_primary_per_patient_rho.csv"))

# ---- 6. Component-Level Analysis (5 components, BH-corrected) ---------------
cat("\n=== Component-Level Analysis ===\n")

component_results <- data.frame(
  Component = names(fate_components),
  n_positive = NA_integer_,
  n_negative = NA_integer_,
  n_total = NA_integer_,
  median_rho = NA_real_,
  wilcoxon_p = NA_real_,
  stringsAsFactors = FALSE
)

for (i in seq_along(fate_components)) {
  comp <- names(fate_components)[i]
  comp_rho <- per_patient_spearman(
    hypoxia_score, component_scores[, comp], meta_mal$Patient
  )
  wt <- signed_rank_test(comp_rho$rho)
  component_results$n_positive[i] <- wt$n_positive
  component_results$n_negative[i] <- wt$n_negative
  component_results$n_total[i]   <- wt$n_total
  component_results$median_rho[i] <- wt$median
  component_results$wilcoxon_p[i] <- wt$p_value

  cat(sprintf("  %s: %d/%d positive, median rho = %.4f, p = %.4e\n",
              comp, wt$n_positive, wt$n_total, wt$median, wt$p_value))
}

## BH correction across 5 components (secondary family)
component_results$q_BH <- bh_correct(component_results$wilcoxon_p)
cat(sprintf("  BH-corrected q-values: %s\n",
            paste(sprintf("%s=%.4f", component_results$Component,
                          component_results$q_BH), collapse = ", ")))

## CAUTION: do NOT validate this against the archived
 ## results/gateA_component_summary.csv -- see header warning above,
## that file is stale (pre score_genes-to-mean fix). Validate instead against
## qa_sensitivity_scoring.csv's "__mean__" rows (Fate_<Component>__mean__hyp_mean).
fwrite(component_results, file.path(results_dir, "gateA_component_summary.csv"))

# ---- 7. Per-Gene Spearman (for Figure 2B) -----------------------------------
cat("\n=== Per-Gene Analysis ===\n")

per_gene_results <- data.frame(
  Gene = glutamine_13,
  n_positive = NA_integer_,
  n_negative = NA_integer_,
  n_total = NA_integer_,
  median_rho = NA_real_,
  stringsAsFactors = FALSE
)

for (g in glutamine_13) {
  if (!(g %in% colnames(expr_mal))) next
  gene_expr <- expr_mal[, g]
  gene_rho <- per_patient_spearman(hypoxia_score, gene_expr, meta_mal$Patient)
  wt <- signed_rank_test(gene_rho$rho)
  idx <- match(g, per_gene_results$Gene)
  per_gene_results$n_positive[idx] <- wt$n_positive
  per_gene_results$n_negative[idx] <- wt$n_negative
  per_gene_results$n_total[idx]   <- wt$n_total
  per_gene_results$median_rho[idx] <- wt$median
}

## CAUTION: same stale-file caveat as Section 6 -- do NOT validate against the
 ## archived results/gateA_per_gene_rho.csv (pre-fix, score_genes-based).
fwrite(per_gene_results, file.path(results_dir, "gateA_per_gene_rho.csv"))

# ---- 8. Synthesis vs Catabolism Contrast ------------------------------------
cat("\n=== Synthesis vs Catabolism Contrast ===\n")

## *** BUG-AUDIT NOTE (resolved this revision) ***
## This is a THIRD instance of the score_genes-vs-arithmetic-mean split that
## defines BUG #1 (see header + Sections 6/7 comments). component_scores here
## is built with score_module() (rowMeans(), i.e. arithmetic mean), so this
## block reproduces the AUTHORITATIVE frozen file qa_lin_contrast_mean.csv
## (24/28 synthesis-favored, median D = 0.1166, Wilcoxon p = 1.10e-05) -- which
## matches the manuscript text exactly ("24/28 tumors, median D = 0.117,
## P < 0.0001"; Results and Fig. 2C legend).
## It does NOT reproduce the stale, score_genes-based frozen gateA_contrast.csv
## (16/28 synthesis-favored, p = 0.0946, NOT significant) -- confirmed by
## direct re-computation of both frozen files with scipy.stats.wilcoxon.
## The output filename below is therefore changed from "gateA_contrast.csv"
## to "qa_lin_contrast_mean.csv" to point at the correct frozen counterpart
## and avoid silently colliding with (and appearing to validate against) the
## stale file. Do NOT treat the on-disk gateA_contrast.csv as a target for
## validating this section -- it is a stale, pre-fix artifact (see BUG #1).
syn_rho <- per_patient_spearman(
  hypoxia_score, component_scores[, "Synthesis"], meta_mal$Patient
)
cat_rho <- per_patient_spearman(
  hypoxia_score, component_scores[, "Catabolism"], meta_mal$Patient
)

## Match patients
common_patients <- intersect(syn_rho$patient, cat_rho$patient)
syn_vals <- syn_rho$rho[match(common_patients, syn_rho$patient)]
cat_vals <- cat_rho$rho[match(common_patients, cat_rho$patient)]
D <- syn_vals - cat_vals

contrast_test <- signed_rank_test(D)
n_syn_favored <- sum(D > 0)
cat(sprintf("  Synthesis-favored: %d/%d patients\n",
            n_syn_favored, length(D)))
cat(sprintf("  Median D: %.4f\n", contrast_test$median))
cat(sprintf("  Wilcoxon p (two-sided): %.4e\n", contrast_test$p_value))

contrast_df <- data.frame(
  Patient = common_patients,
  rho_Synthesis = syn_vals,
  rho_Catabolism = cat_vals,
  D = D,
  D_direction = ifelse(D > 0, "synthesis_favored", "catabolism_favored")
)
fwrite(contrast_df, file.path(results_dir, "qa_lin_contrast_mean.csv"))

# ---- 9. Within-State Analysis -----------------------------------------------
cat("\n=== Within-State Analysis ===\n")

## *** BUG-AUDIT WARNING (fixed in this revision, do not skip) ***
## The ORIGINAL version of this section computed only a 4-row aggregated
## summary and wrote it to `qa_malignant_state.csv`. That is WRONG on two
## counts, confirmed by inspecting the real files on disk:
##   1. The real `qa_malignant_state.csv` is a PER-PATIENT-PER-STATE file
##      (columns Patient,State,rho,direction,n_cells; 115 data rows), and it
##      ADDITIONALLY includes State="ALL" rows (one per patient, 28 of them --
##      the same 11-gene primary-endpoint rho as Section 5).
##   2. The aggregated per-state summary the old code actually produced
##      belongs in a SEPARATE file, `qa_malignant_state_summary.csv`
##      (columns State,n_patients,n_positive,n_negative,median_rho,
##      wilcoxon_p_twosided), which itself also has a frozen "ALL" row.
## The frozen "ALL" row (n=28, 27 positive, median rho=0.16189,
## p=1.49e-8) matches -- to full float64 precision -- BOTH
## qa_endpoint_consistency.csv's `Lin_11gene` row AND
## qa_sensitivity_scoring.csv's `Overall_11__mean__hyp_mean` row. Three
## independently-named frozen files agreeing exactly is strong evidence this
## is correct ground truth for the primary endpoint.
## This revision builds BOTH real files correctly. RESOLVED: the per-state
## minimum-cell threshold is MIN_STATE_CELLS = 20, taken from the original
## Python script qa_steps4_5.py (`if n_state >= MIN_STATE_CELLS`, = 20).
## Re-running from the raw h5ad with 20 reproduces the frozen denominators
## (AC=25, MES=25, OPC=19, NPC=18), positives, medians and P-values exactly
## (|diff| < 1e-16). The earlier default of 10 was WRONG (it would give
## AC=27, MES=25, OPC=22, NPC=21 patients).

per_patient_state_list <- list()

## "ALL" rows: reuse the primary-endpoint per-patient rho from Section 5
## (same 28 patients, same 11-gene score -- do not recompute)
all_rows <- data.frame(
  Patient   = patient_rho$patient,
  State     = "ALL",
  rho       = patient_rho$rho,
  direction = patient_rho$direction,
  n_cells   = patient_rho$n_cells,
  stringsAsFactors = FALSE
)
all_rows <- all_rows[!is.na(all_rows$rho), ]
per_patient_state_list[["ALL"]] <- all_rows

state_summary <- data.frame(
  State = c("ALL", malignant_states),
  n_patients = NA_integer_,
  n_positive = NA_integer_,
  n_negative = NA_integer_,
  median_rho = NA_real_,
  wilcoxon_p_twosided = NA_real_,
  stringsAsFactors = FALSE
)

all_test <- signed_rank_test(all_rows$rho)
state_summary[state_summary$State == "ALL",
              c("n_patients", "n_positive", "n_negative",
                "median_rho", "wilcoxon_p_twosided")] <-
  list(all_test$n_total, all_test$n_positive, all_test$n_negative,
       all_test$median, all_test$p_value)
cat(sprintf("  ALL: %d patients, %d/%d positive, median rho=%.5f, p=%.4e\n",
            all_test$n_total, all_test$n_positive, all_test$n_total,
            all_test$median, all_test$p_value))

for (st in malignant_states) {
  mask <- meta_mal$annotation == st
  state_rho <- per_patient_spearman(
    hypoxia_score[mask], glutamine_11_score[mask],
    meta_mal$Patient[mask],
    min_cells = 20   # MIN_STATE_CELLS in qa_steps4_5.py -- see note above
  )
  state_rho <- state_rho[!is.na(state_rho$rho), ]

  per_patient_state_list[[st]] <- data.frame(
    Patient   = state_rho$patient,
    State     = st,
    rho       = state_rho$rho,
    direction = state_rho$direction,
    n_cells   = state_rho$n_cells,
    stringsAsFactors = FALSE
  )

  wt <- signed_rank_test(state_rho$rho)
  state_summary[state_summary$State == st,
                c("n_patients", "n_positive", "n_negative",
                  "median_rho", "wilcoxon_p_twosided")] <-
    list(wt$n_total, wt$n_positive, wt$n_negative, wt$median, wt$p_value)
  cat(sprintf("  %s: %d patients, %d/%d positive, median rho=%.5f, p=%.4e\n",
              st, wt$n_total, wt$n_positive, wt$n_total, wt$median, wt$p_value))
}

qa_malignant_state <- do.call(rbind, per_patient_state_list)
rownames(qa_malignant_state) <- NULL
fwrite(qa_malignant_state, file.path(results_dir, "qa_malignant_state.csv"))
fwrite(state_summary, file.path(results_dir, "qa_malignant_state_summary.csv"))

## *** VALIDATION: computed vs. frozen per-state patient denominators ***
frozen_n_patients <- c(ALL = 28, `AC-like` = 25, `MES-like` = 25,
                        `OPC-like` = 19, `NPC-like` = 18)
cat("\n--- Denominator check vs. frozen qa_malignant_state_summary.csv ---\n")
for (st in state_summary$State) {
  computed <- state_summary$n_patients[state_summary$State == st]
  frozen   <- frozen_n_patients[[st]]
  ## Compare numeric values rather than storage type: computed may be integer
  ## while the frozen lookup is double, although both represent the same n.
  flag <- if (isTRUE(as.numeric(computed) == as.numeric(frozen))) {
    "OK"
  } else {
    "MISMATCH -- check min_cells (should be 20)"
  }
  cat(sprintf("  %-10s computed=%d  frozen=%d  [%s]\n", st, computed, frozen, flag))
}

# ---- 10. 12-Program Landscape (for Figure 1B) -------------------------------
cat("\n=== 12-Program Landscape ===\n")

## *** REPRODUCTION CHOICE-POINT (disclosed, not a bug to silently "fix") ***
## This section scores ALL 12 programs by pure arithmetic mean, which is the
## cleanest, internally-consistent choice. However, a prior manuscript-stage
## review found that the PUBLISHED Figure 1B actually mixes two scoring
## methods across its two panels: Panel A uses arithmetic mean, Panel B
## reuses the original `sc.tl.score_genes()` matrix from the first analysis
## round (explicitly subtitled "Original Phase 1 scoring" in the figure to
## disclose this). That mixing was reviewed and accepted as defensible-with-
## disclosure for the manuscript as published. This R port intentionally does
## NOT replicate that mix -- it produces a single, uniform arithmetic-mean
## landscape. If the goal is an exact pixel/number reproduction of the
## published Figure 1B, Panel B's programs would need to be rescored with
## `sc.tl.score_genes()`-equivalent logic instead (not implemented here).
## Treat this as a deliberate choice, not an oversight.

landscape_rho <- data.frame(
  patient = eligible_patients,
  matrix(NA_real_, nrow = length(eligible_patients),
         ncol = length(metabolic_programs)),
  stringsAsFactors = FALSE
)
colnames(landscape_rho) <- c("patient", names(metabolic_programs))

for (prog in names(metabolic_programs)) {
  prog_rho <- per_patient_spearman(
    hypoxia_score, program_scores[, prog], meta_mal$Patient
  )
  landscape_rho[[prog]] <- prog_rho$rho[match(eligible_patients, prog_rho$patient)]
}

fwrite(landscape_rho, file.path(results_dir, "phase1_rho_matrix.csv"))

cat("\nGate A complete. Results saved to results/ directory.\n")
cat(sprintf("  Primary: %d/%d positive, rho = %.4f, p = %.2e\n",
            primary_test$n_positive, primary_test$n_total,
            primary_test$median, primary_test$p_value))
